#!/usr/bin/env python3
"""Write a per-machine part of an experiment spec: same conditions, cases, goals,
reps and out_dir, only the listed models.

Every run of a model must stay on one machine (paired comparisons are within a
model), so split by model, run each part on its machine, then copy the run
folders into the one out_dir before evaluating (see RUNNING_ON_ANOTHER_MACHINE.md).

    python rag/tools/split_spec.py rag/tools/specs/crag_spec.json workpc llama3.1:8b qwen2.5:7b claude-sonnet-5-5
    python rag/tools/split_spec.py rag/tools/specs/crag_spec.json homepc qwen2.5:14b
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path


def split(spec: dict, name: str, tag: str, models: list[str]) -> dict:
    known = [m["model"] for m in spec["models"]]
    missing = [m for m in models if m not in known]
    if missing:
        raise SystemExit(f"models not in {name}: {missing} (spec has {known})")
    part = copy.deepcopy(spec)
    part["models"] = [m for m in spec["models"] if m["model"] in models]
    part["notes"] = [f"Per-machine part of {name} for the {tag} (generated by rag/tools/split_spec.py; edit "
                     f"{name} and regenerate). Models: {', '.join(models)}."] + list(spec.get("notes", []))
    return part


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) < 3:
        print(__doc__)
        return 2
    src, tag, models = Path(argv[0]), argv[1], argv[2:]
    part = split(json.loads(src.read_text()), src.name, tag, models)
    out = src.with_name(f"{src.stem}_{tag}.json")
    out.write_text(json.dumps(part, indent=2, ensure_ascii=False) + "\n")
    print(f"Wrote {out} ({', '.join(models)}; out_dir {part['out_dir']}, reps {part['reps']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
